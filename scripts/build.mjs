import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
import { transformAsync } from '@babel/core';
import asyncToGenerator from '@babel/plugin-transform-async-to-generator';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const outputs = new Map();
const read = file => readFile(path.join(root, file));
const manifest = JSON.parse(await read('module.json'));
const pkg = JSON.parse(await read('package.json'));
if (manifest.version !== pkg.version) throw new Error('package.json 与 module.json 的 version 必须一致');
if (manifest.apiVersion !== 2 || !Number.isInteger(manifest.versionCode) || manifest.versionCode < 1) {
  throw new Error('模块需要 apiVersion=2 和正整数 versionCode');
}
// The rear-screen host never runs native Promise jobs; card scripts must reach it with
// async/await compiled to generators, which the bridge runtime drives with its own Promise.
async function compileCard(text) {
  const result = await transformAsync(text, {
    babelrc: false, configFile: false, sourceType: 'script', compact: false, sourceMaps: false,
    plugins: [asyncToGenerator],
  });
  return result.code + '\n';
}
async function bundle(sources, output, { compile = false } = {}) {
  let text = '// Generated by scripts/build.mjs; edit src/ instead.\n' +
    (await Promise.all(sources.map(async source => '// ' + source + '\n' + await read(source)))).join('\n;\n');
  if (compile) text = await compileCard(text);
  new vm.Script(text, { filename: output });
  outputs.set(output, Buffer.from(text));
}
await bundle(['src/shared/profile.js', 'src/shared/render.js', 'src/shared/pull-refresh.js', 'src/card.js'], 'card/main.js', { compile: true });
await bundle(['src/shared/profile.js', 'src/shared/render.js', 'src/webui-network.js', 'src/webui.js'], 'webroot/main.js');
await bundle(['src/shared/profile.js', 'src/background.js'], 'background/main.js');
outputs.set('card/index.html', await read('src/card.html'));
for (const name of (await readdir(path.join(root, 'src/assets'))).sort()) {
  const bytes = await read('src/assets/' + name);
  outputs.set('card/assets/' + name, bytes);
  outputs.set('webroot/assets/' + name, bytes);
}
for (const name of (await readdir(path.join(root, 'src/preview-assets'))).sort()) {
  outputs.set('webroot/assets/' + name, await read('src/preview-assets/' + name));
}
let stale = false;
for (const [file, bytes] of outputs) {
  if (check) {
    const existing = await read(file).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (!existing || !bytes.equals(existing)) { console.error('构建产物过期：' + file); stale = true; }
  } else {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await writeFile(path.join(root, file), bytes);
  }
}
if (stale) process.exitCode = 1;
else console.log((check ? '已核对' : '已生成') + ' ' + outputs.size + ' 个模块文件');
